(function () {
  const STORAGE_KEY = "imclean-lang";
  const SUPPORTED = ["en", "fr", "es"];

  function detectLang() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;

    const candidates = [
      ...(navigator.languages || []),
      navigator.language,
      navigator.userLanguage,
    ].filter(Boolean);

    for (const raw of candidates) {
      const code = String(raw).toLowerCase().slice(0, 2);
      if (SUPPORTED.includes(code)) return code;
    }

    return "en";
  }

  function get(obj, path) {
    return path.split(".").reduce((o, k) => (o == null ? o : o[k]), obj);
  }

  function applyLang(lang) {
    if (!SUPPORTED.includes(lang)) lang = "en";
    const dict = window.IMCLEAN_I18N[lang];
    document.documentElement.lang = lang;
    localStorage.setItem(STORAGE_KEY, lang);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = get(dict, key);
      if (val == null) return;
      if (el.hasAttribute("data-i18n-html")) el.innerHTML = val;
      else el.textContent = val;
    });

    document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      const spec = el.getAttribute("data-i18n-attr");
      spec.split(";").forEach((pair) => {
        const [attr, key] = pair.split(":").map((s) => s.trim());
        const val = get(dict, key);
        if (attr && val != null) el.setAttribute(attr, val);
      });
    });

    const page = document.body.dataset.page;
    const metaRoot = page && get(dict, page + ".meta") ? page + ".meta" : "meta";
    const title = get(dict, metaRoot + ".title") || get(dict, "meta.title");
    const desc = get(dict, metaRoot + ".description") || get(dict, "meta.description");
    const ogTitle = get(dict, metaRoot + ".ogTitle") || get(dict, "meta.ogTitle");
    const ogDesc = get(dict, metaRoot + ".ogDescription") || get(dict, "meta.ogDescription");
    if (title) document.title = title;
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && desc) metaDesc.setAttribute("content", desc);
    const ogT = document.querySelector('meta[property="og:title"]');
    if (ogT && ogTitle) ogT.setAttribute("content", ogTitle);
    const ogD = document.querySelector('meta[property="og:description"]');
    if (ogD && ogDesc) ogD.setAttribute("content", ogDesc);
    const ogL = document.querySelector('meta[property="og:locale"]');
    if (ogL) {
      ogL.setAttribute(
        "content",
        lang === "fr" ? "fr_FR" : lang === "es" ? "es_ES" : "en_US"
      );
    }

    document.querySelectorAll(".lang-switch button").forEach((btn) => {
      const on = btn.dataset.lang === lang;
      btn.classList.toggle("on", on);
      btn.setAttribute("aria-pressed", on ? "true" : "false");
    });
  }

  window.imcleanSetLang = applyLang;
  window.imcleanDetectLang = detectLang;

  function boot() {
    applyLang(detectLang());
    document.querySelectorAll(".lang-switch button").forEach((btn) => {
      btn.addEventListener("click", () => applyLang(btn.dataset.lang));
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot);
  } else {
    boot();
  }
})();
